export function searchImages(query: string): StockImage[] {
  if (!query.trim()) return allImages;
  const q = query.toLowerCase().trim();
  return allImages.filter(
    (img) =>
      img.title.toLowerCase().includes(q) ||
      img.description.toLowerCase().includes(q) ||
      img.category.toLowerCase().includes(q) ||
      img.tags.some((t) => t.toLowerCase().includes(q))
  );
}

export function getImagesByCategory(category: string): StockImage[] {
  if (category === 'all') return allImages;
  return allImages.filter((img) => img.category === category);
}

export function getRelatedImages(image: StockImage, count = 4): StockImage[] {
  return allImages
    .filter(
      (img) =>
        img.id !== image.id &&
        (img.category === image.category ||
          img.tags.some((t) => image.tags.includes(t)))
    )
    .slice(0, count);
}

