export interface StockImage {
  id: string;
  title: string;
  description: string;
  url: string;
  thumbnail: string;
  width: number;
  height: number;
  author: string;
  downloads: number;
  likes: number;
  category: string;
  tags: string[];
  credits: number;
}

function u(id: string, title: string, tags: string[], category: string, author: string, w = 800, h = 600): StockImage {
  return {
    id,
    title,
    description: title,
    url: `https://picsum.photos/seed/${id}/${w}/${h}`,
    thumbnail: `https://picsum.photos/seed/${id}/400/300`,
    width: w,
    height: h,
    author,
    downloads: Math.floor(Math.random() * 5000) + 100,
    likes: Math.floor(Math.random() * 500) + 10,
    category,
    tags,
    credits: 3,
  };
}

